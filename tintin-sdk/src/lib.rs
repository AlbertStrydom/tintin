//! # TinTin Mini-App SDK
//!
//! This crate provides the core types and runtime logic for the
//! TinTin Mini-App system — a sandboxed WebView-based third-party
//! app platform, inspired by WeChat Mini Programs.
//!
//! **License:** MIT — third-party developers may freely use this SDK.
//!
//! ## Overview
//!
//! A mini-app is a signed ZIP archive (`.tma`) containing HTML, CSS,
//! and JavaScript, loaded into a sandboxed WebView. Communication with
//! the host app goes through a typed JS bridge (`window.TinTin`).
//!
//! This crate defines the wire-format types for that bridge, the
//! manifest format, permission model, and sandbox configuration.

use serde::{Deserialize, Serialize};

// ═══════════════════════════════════════════════════════════════════
// Manifest
// ═══════════════════════════════════════════════════════════════════

/// Parsed `manifest.json` from a `.tma` package.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MiniAppManifest {
    pub app_id: String,
    pub name: String,
    pub version: String,
    #[serde(default)]
    pub description: String,
    pub icon: String,
    #[serde(default = "default_entry")]
    pub entry: String,
    #[serde(default)]
    pub permissions: Vec<String>,
    #[serde(default)]
    pub size_bytes: u64,
    #[serde(default)]
    pub developer: Option<DeveloperInfo>,
}

fn default_entry() -> String {
    "index.html".to_string()
}

/// Developer metadata from the manifest.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DeveloperInfo {
    pub name: String,
    #[serde(default)]
    pub website: String,
}

// ═══════════════════════════════════════════════════════════════════
// Permission model
// ═══════════════════════════════════════════════════════════════════

/// Well-known permission identifiers.
pub mod permissions {
    pub const PROFILE_READ: &str = "user.profile.read";
    pub const LOCATION: &str = "user.location";
    pub const SEND_MESSAGE: &str = "message.send";
    pub const CAMERA: &str = "media.camera";
    pub const GALLERY: &str = "media.gallery";
    pub const NETWORK: &str = "network.request";
}

/// A set of granted permissions for a running mini-app.
#[derive(Debug, Clone, Default)]
pub struct PermissionSet {
    granted: std::collections::HashSet<String>,
}

impl PermissionSet {
    pub fn new() -> Self {
        Self::default()
    }

    /// Grant a permission (from manifest or user consent).
    pub fn grant(&mut self, perm: &str) {
        self.granted.insert(perm.to_string());
    }

    /// Check whether a permission is granted.
    pub fn check(&self, perm: &str) -> bool {
        self.granted.contains(perm)
    }

    /// Return all currently granted permissions.
    pub fn list(&self) -> Vec<&str> {
        let mut v: Vec<&str> = self.granted.iter().map(|s| s.as_str()).collect();
        v.sort();
        v
    }
}

// ═══════════════════════════════════════════════════════════════════
// JS Bridge protocol types
// ═══════════════════════════════════════════════════════════════════

/// A request sent from the mini-app WebView to the host.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JsBridgeRequest {
    /// Unique request ID (generated by the mini-app).
    pub id: String,
    /// Method name in dotted notation, e.g. `"user.getProfile"`.
    pub method: String,
    /// Parameters as a JSON object.
    pub params: serde_json::Value,
}

/// A successful response from the host to the mini-app.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JsBridgeResponse {
    /// Matching the request `id`.
    pub id: String,
    /// The result value (any valid JSON).
    pub result: serde_json::Value,
}

/// An error response from the host.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JsBridgeError {
    /// Matching the request `id`.
    pub id: String,
    /// Error details.
    pub error: JsError,
}

/// Error payload for a failed bridge call.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JsError {
    pub code: i32,
    pub message: String,
}

/// Enum over all possible bridge responses.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum JsBridgeOutcome {
    Success(JsBridgeResponse),
    Error(JsBridgeError),
}

