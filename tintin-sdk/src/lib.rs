// Sandbox configuration
// ═══════════════════════════════════════════════════════════════════

/// Configuration for the WebView sandbox environment.
#[derive(Debug, Clone)]
pub struct SandboxConfig {
    /// Base path to the unpacked mini-app directory.
    pub app_dir: String,
    /// Permissions granted to this mini-app.
    pub permissions: PermissionSet,
    /// Maximum storage quota in bytes (default 10 MB).
    pub storage_quota: u64,
    /// Allowed network domains (from manifest or developer config).
    pub allowed_domains: Vec<String>,
}

impl Default for SandboxConfig {
    fn default() -> Self {
        Self {
            app_dir: String::new(),
            permissions: PermissionSet::new(),
            storage_quota: 10 * 1024 * 1024, // 10 MB
            allowed_domains: Vec::new(),
        }
    }
}

impl SandboxConfig {
    /// Create a config from a manifest and the app directory path.
    pub fn from_manifest(manifest: &MiniAppManifest, app_dir: &str) -> Self {
        let mut perms = PermissionSet::new();
        for p in &manifest.permissions {
            perms.grant(p);
        }
        Self {
            app_dir: app_dir.to_string(),
            permissions: perms,
            ..Default::default()
        }
    }
}

// ═══════════════════════════════════════════════════════════════════
// Mini-App Package validation
// ═══════════════════════════════════════════════════════════════════

/// Errors that can occur when validating a mini-app package.
#[derive(Debug, Clone)]
pub enum PackageError {
    InvalidManifest(String),
    MissingEntry,
    IconTooLarge,
    PackageTooLarge,
    PermissionNotRecognized(String),
}

impl std::fmt::Display for PackageError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::InvalidManifest(s) => write!(f, "invalid manifest: {s}"),
            Self::MissingEntry => write!(f, "entry file not found in package"),
            Self::IconTooLarge => write!(f, "icon exceeds maximum size"),
            Self::PackageTooLarge => write!(f, "package exceeds 5 MB limit"),
            Self::PermissionNotRecognized(p) => write!(f, "unknown permission: {p}"),
        }
    }
}

impl std::error::Error for PackageError {}

/// Validate a parsed manifest for consistency.
pub fn validate_manifest(manifest: &MiniAppManifest) -> Result<(), PackageError> {
    if manifest.app_id.is_empty() {
        return Err(PackageError::InvalidManifest("app_id is required".into()));
    }
    if manifest.name.is_empty() {
        return Err(PackageError::InvalidManifest("name is required".into()));
    }
    if manifest.version.is_empty() {
        return Err(PackageError::InvalidManifest("version is required".into()));
    }
    if manifest.icon.is_empty() {
        return Err(PackageError::InvalidManifest("icon is required".into()));
    }
    if manifest.entry.is_empty() {
        return Err(PackageError::InvalidManifest("entry is required".into()));
    }
    if manifest.size_bytes > 5 * 1024 * 1024 {
        return Err(PackageError::PackageTooLarge);
    }
    // Validate known permissions
    let known: &[&str] = &[
        permissions::PROFILE_READ,
        permissions::LOCATION,
        permissions::SEND_MESSAGE,
        permissions::CAMERA,
        permissions::GALLERY,
        permissions::NETWORK,
    ];
    for p in &manifest.permissions {
        if !known.contains(&p.as_str()) {
            return Err(PackageError::PermissionNotRecognized(p.clone()));
        }
    }
    Ok(())
}

