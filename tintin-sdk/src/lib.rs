#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_manifest_roundtrip() {
        let json = r#"{
            "app_id": "com.example.test",
            "name": "Test App",
            "version": "1.0.0",
            "description": "A test",
            "icon": "icon.png",
            "entry": "index.html",
            "permissions": ["user.profile.read"],
            "size_bytes": 1024,
            "developer": { "name": "Dev", "website": "https://example.com" }
        }"#;
        let manifest: MiniAppManifest = serde_json::from_str(json).unwrap();
        assert_eq!(manifest.app_id, "com.example.test");
        assert_eq!(manifest.permissions.len(), 1);
        assert!(manifest.developer.is_some());
    }

    #[test]
    fn test_validate_good_manifest() {
        let m = MiniAppManifest {
            app_id: "com.example.good".into(),
            name: "Good".into(),
            version: "0.1.0".into(),
            description: String::new(),
            icon: "icon.png".into(),
            entry: "index.html".into(),
            permissions: vec!["user.profile.read".into()],
            size_bytes: 100_000,
            developer: None,
        };
        assert!(validate_manifest(&m).is_ok());
    }

    #[test]
    fn test_validate_bad_permission() {
        let m = MiniAppManifest {
            app_id: "com.example.bad".into(),
            name: "Bad".into(),
            version: "0.1.0".into(),
            description: String::new(),
            icon: "icon.png".into(),
            entry: "index.html".into(),
            permissions: vec!["user.secret".into()],
            size_bytes: 100_000,
            developer: None,
        };
        assert!(validate_manifest(&m).is_err());
    }

    #[test]
    fn test_validate_too_large() {
        let m = MiniAppManifest {
            app_id: "com.example.large".into(),
            name: "Large".into(),
            version: "0.1.0".into(),
            description: String::new(),
            icon: "icon.png".into(),
            entry: "index.html".into(),
            permissions: vec![],
            size_bytes: 10_000_000, // 10 MB > 5 MB limit
            developer: None,
        };
        assert!(validate_manifest(&m).is_err());
    }

    #[test]
    fn test_permission_set() {
        let mut ps = PermissionSet::new();
        assert!(!ps.check("user.profile.read"));
        ps.grant("user.profile.read");
        assert!(ps.check("user.profile.read"));
        assert_eq!(ps.list(), vec!["user.profile.read"]);
    }

    #[test]
    fn test_bridge_request_serialize() {
        let req = JsBridgeRequest {
            id: "req_1".into(),
            method: "user.getProfile".into(),
            params: serde_json::json!({}),
        };
        let json = serde_json::to_string(&req).unwrap();
        assert!(json.contains("req_1"));
        assert!(json.contains("user.getProfile"));
    }

    #[test]
    fn test_bridge_outcome_deserialize_success() {
        let json = r#"{"id":"req_1","result":{"id":"alice"}}"#;
        let outcome: JsBridgeOutcome = serde_json::from_str(json).unwrap();
        match outcome {
            JsBridgeOutcome::Success(r) => assert_eq!(r.id, "req_1"),
            _ => panic!("expected Success"),
        }
    }

    #[test]
    fn test_bridge_outcome_deserialize_error() {
        let json = r#"{"id":"req_1","error":{"code":-1,"message":"denied"}}"#;
        let outcome: JsBridgeOutcome = serde_json::from_str(json).unwrap();
        match outcome {
            JsBridgeOutcome::Error(e) => assert_eq!(e.error.code, -1),
            _ => panic!("expected Error"),
        }
    }

    #[test]
    fn test_sandbox_config_from_manifest() {
        let m = MiniAppManifest {
            app_id: "com.example.sbox".into(),
            name: "Sandbox".into(),
            version: "0.1.0".into(),
            description: String::new(),
            icon: "icon.png".into(),
            entry: "index.html".into(),
            permissions: vec!["user.profile.read".into(), "media.camera".into()],
            size_bytes: 50_000,
            developer: None,
        };
        let config = SandboxConfig::from_manifest(&m, "/apps/sbox");
        assert_eq!(config.app_dir, "/apps/sbox");
        assert!(config.permissions.check("user.profile.read"));
        assert!(config.permissions.check("media.camera"));
        assert!(!config.permissions.check("message.send"));
    }
}
